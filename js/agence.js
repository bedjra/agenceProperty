// =====================================================
//  MOTEUR DE LANGUE / LANGUAGE ENGINE
// =====================================================
const LANG_KEY = 'agence-lang';

function getInitialLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && I18N[saved]) return saved;
  } catch (e) { /* stockage indisponible */ }
  return (navigator.language || 'fr').toLowerCase().startsWith('en') ? 'en' : 'fr';
}

function setLang(lang) {
  const t = I18N[lang];
  if (!t) return;

  document.documentElement.lang = lang;

  // Texte simple
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = t[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });
  // Texte avec balises (span, em, &nbsp;…)
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const v = t[el.dataset.i18nHtml];
    if (v !== undefined) el.innerHTML = v;
  });
  // Attributs
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const v = t[el.dataset.i18nAria];
    if (v !== undefined) el.setAttribute('aria-label', v);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const v = t[el.dataset.i18nAlt];
    if (v !== undefined) el.setAttribute('alt', v);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const v = t[el.dataset.i18nTitle];
    if (v !== undefined) el.setAttribute('title', v);
  });

  // Titre + meta description
  document.title = t['meta.title'];
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', t['meta.desc']);

  // Message WhatsApp pré-rempli
  document.querySelectorAll('.wa-link').forEach((a) => {
    a.href = 'https://wa.me/22890458096?text=' + encodeURIComponent(t['wa.msg']);
  });

  // Boutons FR | EN
  document.querySelectorAll('.lang-switch button').forEach((b) => {
    const on = b.dataset.lang === lang;
    b.classList.toggle('active', on);
    b.setAttribute('aria-pressed', on);
  });

  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
}

document.querySelectorAll('.lang-switch button').forEach((b) => {
  b.addEventListener('click', () => setLang(b.dataset.lang));
});

setLang(getInitialLang());

// =====================================================
//  MENU BURGER (mobile)
// =====================================================
const burger = document.getElementById('burgerBtn');
const nav = document.getElementById('mainNav');

function setMenu(open) {
  nav.classList.toggle('open', open);
  burger.setAttribute('aria-expanded', open);
  document.body.style.overflow = open ? 'hidden' : '';
}

burger.addEventListener('click', () => setMenu(!nav.classList.contains('open')));
nav.querySelectorAll('a').forEach((l) => l.addEventListener('click', () => setMenu(false)));
document.addEventListener('keydown', (e) => { if (e.key === 'Escape') setMenu(false); });
window.addEventListener('resize', () => { if (window.innerWidth > 960) setMenu(false); });

// Lien actif selon la section visible
(function () {
  const links = document.querySelectorAll('.main-nav a[href^="#"]');
  const sections = [];

  links.forEach((l) => {
    const el = document.querySelector(l.getAttribute('href'));
    if (el) sections.push({ link: l, el });
  });

  function onScroll() {
    const y = window.scrollY + 120;
    let current = sections[0];
    sections.forEach((s) => { if (s.el.offsetTop <= y) current = s; });
    links.forEach((l) => l.classList.remove('active'));
    if (current) current.link.classList.add('active');
  }

  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();
})();

// Apparition progressive des éléments
(function () {
  const items = document.querySelectorAll('.service-card, .value');
  if (!('IntersectionObserver' in window)) return;

  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('in');
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  items.forEach((el, i) => {
    el.classList.add('reveal');
    el.style.setProperty('--d', (i % 4) * 0.1 + 's');
    io.observe(el);
  });
})();